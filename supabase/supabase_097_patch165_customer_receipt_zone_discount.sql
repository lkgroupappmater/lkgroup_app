-- Customer discount confirmation + receipt priority + zone override rules.

create table if not exists public.customer_zone_overrides (
  id bigint generated by default as identity primary key,
  route_key text not null,
  customer_name text not null,
  zone text not null default '102',
  source_type text not null default 'base_excel',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(route_key, customer_name, source_type)
);

create index if not exists idx_customer_zone_overrides_lookup
  on public.customer_zone_overrides(route_key, active, customer_name);

alter table public.customer_zone_overrides enable row level security;

drop policy if exists customer_zone_overrides_read_authenticated
  on public.customer_zone_overrides;
create policy customer_zone_overrides_read_authenticated
  on public.customer_zone_overrides for select
  to authenticated
  using (true);

create or replace function public.admin_replace_base_zone_overrides(
  p_route_key text,
  p_names jsonb
)
returns integer
language plpgsql
security definer
set search_path=public
as $$
declare
  v_name text;
  v_count integer:=0;
begin
  if coalesce(btrim(p_route_key),'')='' then return 0; end if;

  delete from public.customer_zone_overrides
  where route_key=btrim(p_route_key)
    and source_type='base_excel';

  for v_name in
    select distinct btrim(value)
    from jsonb_array_elements_text(coalesce(p_names,'[]'::jsonb))
    where btrim(value)<>''
  loop
    insert into public.customer_zone_overrides(
      route_key,customer_name,zone,source_type,active,updated_at
    ) values(
      btrim(p_route_key),v_name,'102','base_excel',true,now()
    )
    on conflict(route_key,customer_name,source_type)
    do update set zone='102',active=true,updated_at=now();
    v_count:=v_count+1;
  end loop;

  return v_count;
end
$$;

revoke all on function public.admin_replace_base_zone_overrides(text,jsonb) from public;
grant execute on function public.admin_replace_base_zone_overrides(text,jsonb)
  to authenticated,service_role;

create or replace function public.admin_list_discount_rules_waiting_for_phone()
returns setof jsonb
language sql
stable
security definer
set search_path=public
as $$
  select jsonb_build_object(
    'id',r.id,
    'route_key',coalesce(r.route_key,''),
    'customer_name',coalesce(r.customer_name,''),
    'company_name',coalesce(r.company_name,''),
    'group_name',coalesce(r.group_name,''),
    'discount_percent',coalesce(r.discount_percent,0),
    'notes',coalesce(r.notes,''),
    'source_detail',coalesce(r.source_detail,''),
    'candidate_phone',coalesce(c.candidate_phone,'')
  )
  from public.customer_rate_overrides r
  left join lateral (
    select btrim(coalesce(s.consignee_phone,'')) candidate_phone
    from public.shipments s
    where public.normalize_phone(s.consignee_phone)<>''
      and (r.route_key='all' or public.route_base_key_for_label(s.route)=r.route_key)
      and (
        public.normalize_person_name(s.consignee_name)=public.normalize_person_name(r.customer_name)
        or (
          coalesce(r.company_name,'')<>''
          and public.normalize_person_name(s.consignee_name)=public.normalize_person_name(r.company_name)
        )
      )
    order by s.received_at desc nulls last,s.id desc
    limit 1
  ) c on true
  where coalesce(r.active,false)=false
    and public.normalize_phone(r.phone)=''
    and coalesce(r.discount_percent,0)>0
    and public.normalize_person_name(r.customer_name) not in (
      public.normalize_person_name('박성호'),
      public.normalize_person_name('박성호 대표')
    )
  order by r.route_key,r.group_name,r.customer_name,r.id
$$;

